#!/usr/bin/env python3
"""Generate the checked C++ fixture for the dependency-free native oracle."""

from __future__ import annotations

import argparse
from pathlib import Path
import sys
from typing import Iterable

import numpy as np


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from harpq.integrity import crc32c  # noqa: E402
from harpq.matrix_codec import encode_stage_payload  # noqa: E402
from harpq.quantization import (  # noqa: E402
    ProgressiveQuantizedMatrix,
    dequantize_prefix,
    dequantize_stage,
    progressive_matmul,
    quantize_progressive,
)


DEFAULT_OUTPUT = ROOT / "native" / "tests" / "generated" / "golden_vectors.hpp"


def _fixture() -> tuple[ProgressiveQuantizedMatrix, np.ndarray, np.ndarray]:
    # Integer modular formulas avoid RNG/version drift while exercising a 2x2
    # tile grid, edge padding, multiple rows, and multiple groups per tile.
    rows = np.arange(5, dtype=np.int32)[:, None]
    columns = np.arange(9, dtype=np.int32)[None, :]
    weights = (((rows * 17 + columns * 11) % 31) - 15).astype(np.float32) / 8.0
    weights = np.where((rows + columns) % 7 == 0, 0.0, weights).astype(np.float32)

    batches = np.arange(2, dtype=np.int32)[:, None]
    input_columns = np.arange(9, dtype=np.int32)[None, :]
    inputs = (((batches * 13 + input_columns * 7) % 23) - 11).astype(np.float32) / 8.0
    bias = (np.arange(5, dtype=np.float32) - 2.0) / 8.0
    quantized = quantize_progressive(
        weights,
        tile_shape=(4, 8),
        group_size=4,
        stage_count=4,
    )
    return quantized, inputs, bias


def _float_literal(value: np.generic | float) -> str:
    scalar = float(np.float32(value))
    return f"{scalar.hex()}F"


def _wrapped_values(values: Iterable[str], *, indent: str = "    ") -> str:
    items = list(values)
    lines: list[str] = []
    for start in range(0, len(items), 8):
        lines.append(indent + ", ".join(items[start : start + 8]))
    return ",\n".join(lines)


def _array(name: str, cxx_type: str, values: Iterable[str]) -> str:
    items = list(values)
    return (
        f"inline constexpr std::array<{cxx_type}, {len(items)}> {name}{{{{\n"
        f"{_wrapped_values(items)}\n"
        "}};\n"
    )


def _scalar_progressive_linear(
    quantized: ProgressiveQuantizedMatrix,
    inputs: np.ndarray,
    bias: np.ndarray,
    prefix: int,
) -> np.ndarray:
    """Use an explicit FP32 order so the checked fixture is BLAS-independent."""

    output = np.zeros((inputs.shape[0], quantized.original_shape[0]), dtype=np.float32)
    for stage_index in range(prefix):
        weights = dequantize_stage(quantized, stage_index)
        for batch in range(inputs.shape[0]):
            for row in range(quantized.original_shape[0]):
                dot = np.float32(0.0)
                for column in range(quantized.original_shape[1]):
                    product = np.float32(inputs[batch, column] * weights[row, column])
                    dot = np.float32(dot + product)
                output[batch, row] = np.float32(output[batch, row] + dot)
    output = np.float32(output + bias)

    # The fixture fixes operation order; the public NumPy oracle may dispatch
    # to a platform BLAS and is therefore compared with its documented tolerance.
    np.testing.assert_allclose(
        output,
        progressive_matmul(inputs, quantized, prefix=prefix, bias=bias),
        rtol=1e-5,
        atol=1e-5,
    )
    return output


def render_header() -> str:
    quantized, inputs, bias = _fixture()
    payloads = [
        encode_stage_payload(stage, stage_index)
        for stage_index, stage in enumerate(quantized.stages)
    ]
    payload_lengths = {len(payload) for payload in payloads}
    if len(payload_lengths) != 1:
        raise RuntimeError("golden stages unexpectedly have different payload lengths")
    payload_length = payload_lengths.pop()

    prefix_weights = [
        dequantize_prefix(quantized, prefix).reshape(-1)
        for prefix in range(quantized.stage_count + 1)
    ]
    prefix_outputs = [
        _scalar_progressive_linear(quantized, inputs, bias, prefix).reshape(-1)
        for prefix in range(quantized.stage_count + 1)
    ]

    lines = [
        "// Generated by scripts/generate_native_golden.py. DO NOT EDIT.",
        "#ifndef HARPQ_NATIVE_TESTS_GENERATED_GOLDEN_VECTORS_HPP_",
        "#define HARPQ_NATIVE_TESTS_GENERATED_GOLDEN_VECTORS_HPP_",
        "",
        "#include <array>",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        '#include "harpq/native/stage_codec.hpp"',
        "",
        "namespace harpq::native_runtime::golden {",
        "",
        "inline constexpr std::size_t kStageCount = 4;",
        "inline constexpr std::size_t kPrefixCount = kStageCount + 1;",
        f"inline constexpr std::size_t kPayloadBytes = {payload_length};",
        "inline constexpr std::size_t kBatchSize = 2;",
        f"inline constexpr MatrixGeometry kGeometry{{{quantized.original_shape[0]}, "
        f"{quantized.original_shape[1]}, {quantized.padded_shape[0]}, "
        f"{quantized.padded_shape[1]}, {quantized.tile_shape[0]}, "
        f"{quantized.tile_shape[1]}, {quantized.group_size}}};",
        "inline constexpr ScaleShape kScaleShape{" + ", ".join(
            str(dimension) for dimension in quantized.stages[0].scales.shape
        ) + "};",
        "",
        "inline constexpr std::array<std::array<std::uint8_t, kPayloadBytes>, "
        "kStageCount> kStagePayloads{{",
    ]
    for payload in payloads:
        lines.extend(
            [
                "  {{",
                _wrapped_values((f"0x{byte:02x}" for byte in payload), indent="    "),
                "  }},",
            ]
        )
    lines.extend(
        [
            "}};",
            "",
            _array(
                "kStageCrc32c",
                "std::uint32_t",
                (f"0x{crc32c(payload):08x}U" for payload in payloads),
            ).rstrip(),
            "",
            _array("kInputs", "float", (_float_literal(value) for value in inputs.reshape(-1))).rstrip(),
            "",
            _array("kBias", "float", (_float_literal(value) for value in bias)).rstrip(),
            "",
            "inline constexpr std::array<",
            "    std::array<float, kGeometry.original_rows * kGeometry.original_columns>,",
            "    kPrefixCount> kPrefixWeights{{",
        ]
    )
    for weights in prefix_weights:
        lines.extend(
            [
                "  {{",
                _wrapped_values((_float_literal(value) for value in weights), indent="    "),
                "  }},",
            ]
        )
    lines.extend(
        [
            "}};",
            "",
            "inline constexpr std::array<",
            "    std::array<float, kBatchSize * kGeometry.original_rows>,",
            "    kPrefixCount> kPrefixOutputs{{",
        ]
    )
    for output in prefix_outputs:
        lines.extend(
            [
                "  {{",
                _wrapped_values((_float_literal(value) for value in output), indent="    "),
                "  }},",
            ]
        )
    lines.extend(
        [
            "}};",
            "",
            "}  // namespace harpq::native_runtime::golden",
            "",
            "#endif  // HARPQ_NATIVE_TESTS_GENERATED_GOLDEN_VECTORS_HPP_",
            "",
        ]
    )
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail instead of writing when the checked header has drifted",
    )
    args = parser.parse_args(argv)
    rendered = render_header()
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != rendered:
            print(
                f"native golden header drifted; run {Path(__file__).name} --output {args.output}",
                file=sys.stderr,
            )
            return 1
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(rendered, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
